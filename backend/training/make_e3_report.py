"""Renders docs/E3_RESULTS.md from docs/results/e3_modern/{e3_selection.json,e3_data.json} (all numbers come from those files) and applies the FROZEN promotion rule
of docs/E3_PROTOCOL.md programmatically. It changes no threshold and no criterion.   python -X utf8 backend/training/make_e3_report.py"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "docs" / "results" / "e3_modern"
OUT = ROOT / "docs" / "E3_RESULTS.md"
RUNS = ["e3a_modern_qa0.5", "e3b_modern_noQA", "model4", "v2"]
LABEL = {"e3a_modern_qa0.5": "E3A (quality aug 0.5)", "e3b_modern_noQA": "E3B (no quality aug)", "model4": "Model 4 (current default)", "v2": "v2 (production, DeepFakeFace only)"}
VIDEO_REAL, VIDEO_FAKE = 91, 56            # Celeb-DF held-out videos (docs/FOUR_MODEL_COMPARISON.md): n = 147


def wilson(k: float, n: int, z: float = 1.96):
    if n <= 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return c - h, c + h


def flagged(v: dict) -> float:
    """share of crops called FAKE. evaluate.py reports it as fake_detection_rate, or as 1 - real_acceptance_rate for the generator literally named 'real'."""
    return v["fake_detection_rate"] if "fake_detection_rate" in v else 1.0 - v["real_acceptance_rate"]


def rate(p: float, n: int) -> str:
    lo, hi = wilson(round(p * n), n)
    return f"{p:.3f} [{lo:.3f}, {hi:.3f}]"


def main() -> None:
    sel = json.loads((RES / "e3_selection.json").read_text(encoding="utf-8"))
    data = json.loads((RES / "e3_data.json").read_text(encoding="utf-8"))
    T = {r["run"]: r for r in sel["table"]}

    def counts(run, split):                      # (n_real, n_fake) from the per-generator table of that split
        pg = T[run][f"{split}_none_per_generator"]
        nr = sum(v["n"] for g, v in pg.items() if g.startswith("real"))
        return nr, sum(v["n"] for v in pg.values()) - nr

    L: list[str] = []
    a = L.append
    a("# E3 results: modern-generator training\n")
    a("Generated by `backend/training/make_e3_report.py` from `docs/results/e3_modern/` (Kaggle notebook `iamankoo/verif-ai-e3`, Tesla T4, seed 42; checkpoints and metrics only were exported). Protocol and promotion rule: `docs/E3_PROTOCOL.md` (written before training). Threshold 0.5 everywhere; nothing was tuned on any test split. Intervals are Wilson 95% on the exact counts.\n")
    a("## 1. Data actually used\n")
    pl, kp = data["planned"], data["kept"]
    a("| Split / source | planned | kept after face filter |\n|---|---|---|")
    for k in pl:
        a(f"| {k} | {pl[k]} | {kp.get(k, 0)} |")
    a(f"\nNear-duplicates removed against training crops of all sources: **validation {data['leaks_removed'].get('val', 0)}**, **modern_test {data['leaks_removed'].get('modern_test', 0)}** crops. Training also used the DeepFakeFace and Celeb-DF training crops exactly as for Model 4.\n")
    a("Sharpness (variance of Laplacian, median) of the crops actually used: " + "; ".join(f"{k} {v['lap_var_p10_50_90'][1]}" for k, v in data["sharpness"].items() if k.startswith(("train/real_ffhq", "train/deepdetect", "train/sfhq", "modern_test", "train/real", "train/celebdf"))) + ".\n")
    a(f"## 2. Candidate selection (validation only)\n\nSelected by the pre-declared rule: **{sel['selected']}** (validation clean/degraded mean ROC-AUC {T[sel['selected']]['val_select']:.3f}; E3B {T['e3b_modern_noQA']['val_select']:.3f}). Best epochs: E3A {T['e3a_modern_qa0.5']['best_epoch']}, E3B {T['e3b_modern_noQA']['best_epoch']}.\n")
    a("## 3. Frame-level results, clean (FPR = real called FAKE, FNR = fake called REAL)\n")
    a("| Split | Model | n real / fake | Accuracy | ROC-AUC | FPR [95% CI] | FNR [95% CI] |\n|---|---|---|---|---|---|---|")
    for sp in ("val", "test_internal", "test_crossgen", "cdf_test", "modern_test"):
        for run in RUNS:
            m = T[run][f"{sp}_none"]
            nr, nf = counts(run, sp)
            a(f"| {sp} | {LABEL[run]} | {nr} / {nf} | {m['accuracy']:.3f} | {m['roc_auc']:.3f} | {rate(m['false_positive_rate'], nr)} | {rate(m['false_negative_rate'], nf)} |")
    a("\n## 4. Video-level (Celeb-DF held-out identities; 91 real, 56 fake videos), clean\n")
    a("| Model | Accuracy | ROC-AUC | FPR (real videos called FAKE) [95% CI] | FNR (fake videos called REAL) [95% CI] |\n|---|---|---|---|---|")
    for run in RUNS:
        m = T[run]["cdf_test_none_VIDEO"]
        a(f"| {LABEL[run]} | {m['accuracy']:.3f} | {m['roc_auc']:.3f} | {rate(m['false_positive_rate'], VIDEO_REAL)} | {rate(m['false_negative_rate'], VIDEO_FAKE)} |")
    a("\n## 5. Per generator / source, clean (share of crops called FAKE: for real sources this is the FPR, for fake sources it is the detection rate)\n")
    a("| Split | Source | n | " + " | ".join(LABEL[r] for r in RUNS) + " |\n|---|---|---|" + "---|" * len(RUNS))
    for sp in ("modern_test", "test_internal", "test_crossgen", "cdf_test"):
        for g, v in sorted(T["v2"][f"{sp}_none_per_generator"].items()):
            cells = " | ".join(rate(flagged(T[r][f"{sp}_none_per_generator"][g]), v["n"]) for r in RUNS)
            a(f"| {sp} | {g} | {v['n']} | {cells} |")
    a("\n## 6. Robustness: class-blind 'mixed' degradation (blur / down-up / noise)\n")
    a("| Model | modern_test accuracy | modern_test FPR | modern_test FNR | Celeb-DF video accuracy | video FPR |\n|---|---|---|---|---|---|")
    for run in RUNS:
        m, v = T[run]["modern_test_mixed"], T[run]["cdf_test_mixed_VIDEO"]
        a(f"| {LABEL[run]} | {m['accuracy']:.3f} | {m['false_positive_rate']:.3f} | {m['false_negative_rate']:.3f} | {v['accuracy']:.3f} | {v['false_positive_rate']:.3f} |")
    # ---- frozen promotion rule
    e, m4, v2 = T[sel["selected"]], T["model4"], T["v2"]
    c1 = e["cdf_test_none_VIDEO"]["false_positive_rate"] <= m4["cdf_test_none_VIDEO"]["false_positive_rate"] + 0.03 and e["cdf_test_none_VIDEO"]["accuracy"] >= 0.95
    c2s = {sp: (e[f"{sp}_none"]["false_negative_rate"], v2[f"{sp}_none"]["false_negative_rate"] + 0.05, e[f"{sp}_none"]["false_positive_rate"]) for sp in ("test_internal", "test_crossgen")}
    c2 = all(fnr <= lim and fpr <= 0.20 for fnr, lim, fpr in c2s.values())
    ba = lambda r: 1 - (r["modern_test_none"]["false_positive_rate"] + r["modern_test_none"]["false_negative_rate"]) / 2
    nr, nf = counts(sel["selected"], "modern_test")
    def se(r):                                   # standard error of balanced accuracy = (specificity + sensitivity) / 2, binomial variances
        m = r["modern_test_none"]; p, q = m["false_positive_rate"], m["false_negative_rate"]
        return math.sqrt((p * (1 - p) / nr + q * (1 - q) / nf) / 4)
    diff = ba(e) - ba(m4)
    lo = diff - 1.96 * math.sqrt(se(e) ** 2 + se(m4) ** 2)          # lower end of an approximate 95% interval for the difference
    c3 = diff >= 0.10 and lo > 0
    a("\n## 7. The frozen promotion rule (`docs/E3_PROTOCOL.md`), applied\n")
    a("| # | Criterion | Value for " + sel["selected"] + " | Result |\n|---|---|---|---|")
    a(f"| 1 | Celeb-DF video FPR <= Model 4's FPR + 0.03 and video accuracy >= 0.95 | FPR {e['cdf_test_none_VIDEO']['false_positive_rate']:.3f} vs Model 4 {m4['cdf_test_none_VIDEO']['false_positive_rate']:.3f}; accuracy {e['cdf_test_none_VIDEO']['accuracy']:.3f} | **{'PASS' if c1 else 'FAIL'}** |")
    for sp, (fnr, lim, fpr) in c2s.items():
        a(f"| 2 | DeepFakeFace `{sp}`: FNR <= v2's FNR + 0.05 and FPR <= 0.20 | FNR {fnr:.3f} (limit {lim:.3f}); FPR {fpr:.3f} | **{'PASS' if (fnr <= lim and fpr <= 0.20) else 'FAIL'}** |")
    a(f"| 3 | `modern_test` balanced accuracy at least 0.10 above Model 4, interval above 0 | {ba(e):.3f} vs {ba(m4):.3f} (difference {diff:+.3f}, 95% lower bound {lo:+.3f}) | **{'PASS' if c3 else 'FAIL'}** |")
    promote = c1 and c2 and c3
    a(f"\n**Outcome under the frozen rule: {'PROMOTE' if promote else 'DO NOT PROMOTE - Model 4 stays the default'}.**\n")
    if not promote:
        a("Criterion 2 fails for the selected model. It fails for Model 4 as well (Model 4's FNR on the same splits is "
          f"{m4['test_internal_none']['false_negative_rate']:.3f} and {m4['test_crossgen_none']['false_negative_rate']:.3f}; v2's {v2['test_internal_none']['false_negative_rate']:.3f} and {v2['test_crossgen_none']['false_negative_rate']:.3f}). "
          "The criteria were not relaxed after the results were seen. The selected checkpoint is preserved and recommended for the owner's decision (section 9).\n")
    a("## 8. What these numbers do and do not show\n")
    a("* On `modern_test` the E3 models detect almost all SFHQ and DeepDetect fakes while Model 4 and v2 detect almost none; Celeb-DF video accuracy is unchanged (0.98); DeepFakeFace detection is about as poor as Model 4's, and clearly worse than v2's.")
    a("* `modern_test` is **not** a generator-disjoint test: its fakes come from the same generator families as the training fakes (DeepDetect has no per-image generator labels), and its reals are FFHQ only, so a real-source/fake-source style shortcut cannot be excluded. The only unseen-generator test is DeepFakeFace `test_crossgen`, where E3 does **not** improve on Model 4.")
    a("* Therefore the high `modern_test` accuracy must **not** be read as a general ability to detect modern AI images or video. No labelled modern AI-video data was available, so nothing is claimed about AI video.")
    a("* Frame-level results are on face crops from three real-image sources and a handful of generators; the intervals above reflect sampling error only, not dataset bias.\n")
    ck = ROOT / "backend" / "runs" / "e3" / "e3a_modern_qa0.5_best.pth"
    sha = hashlib.sha256(ck.read_bytes()).hexdigest() if ck.is_file() else "(checkpoint not present locally)"
    a(f"## 9. Checkpoints\n\n* E3A `backend/runs/e3/e3a_modern_qa0.5_best.pth`, SHA-256 `{sha}` (not committed; git-ignored).\n* Model 4 and v2 are unchanged.\n")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT, "| criteria:", dict(c1=c1, c2=c2, c3=c3), "| promote:", promote)


if __name__ == "__main__":
    main()
