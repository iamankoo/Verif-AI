"""Builds the E4 tables of the report from the verified E4 metrics (report/data/e4_selection.json, copied unchanged from the Kaggle
results zip verifai_e4_results.zip: results/e4_selection.json). Output: report/tables/e4_tables.tex.   python report/scripts/make_e4_tables.py"""
import json
from pathlib import Path
import make_tables as mt

ROOT = Path(__file__).resolve().parents[1]
sel = json.loads((ROOT / "data" / "e4_selection.json").read_text(encoding="utf-8"))
cand = sel["selected"]
mt.NAME[cand] = "E4"
runs = [cand, "model4", "v2"]
T = {r["run"]: r for r in sel["table"]}
_, T, counts = mt.build(sel, runs, "e4")
promo, promoted = mt.promotion(sel, T, counts, cand)

rows = [("DFF internal test (frames)", "test_internal_none"), ("DFF cross-generator test (frames)", "test_crossgen_none"),
        ("Celeb-DF test (frames)", "cdf_test_none"), ("Celeb-DF test (\\textbf{video})", "cdf_test_none_VIDEO"), ("modern\\_test (frames)", "modern_test_none")]
L = ["\\begin{table}[ht]\\centering\\caption[Experiment E4 against Model 4 and v2: held-out results]{Experiment E4 against Model 4 and v2: held-out results, clean inputs, fixed threshold 0.5 (accuracy/ROC-AUC/FPR/FNR).}\\label{tab:e4-key}\\footnotesize",
     "\\begin{tabular}{|l|c|c|c|}\\hline \\textbf{Test set} & \\textbf{E4} & \\textbf{Model 4} & \\textbf{v2} \\\\ \\hline"]
for name, key in rows:
    cells = []
    for r in runs:
        m = T[r][key]
        cells.append(f"{m['accuracy']:.3f}/{m['roc_auc']:.3f}/{m['false_positive_rate']:.3f}/{m['false_negative_rate']:.3f}")
    L.append(f"{name} & " + " & ".join(cells) + " \\\\ \\hline")
L.append("\\end{tabular}\\end{table}\n")
body = "\n".join(L).replace("\\begin{tabular}", "\\begin{adjustbox}{max width=\\linewidth,center}\\begin{tabular}").replace("\\end{tabular}", "\\end{tabular}\\end{adjustbox}")
promo = promo.replace("\\begin{tabular}", "\\begin{adjustbox}{max width=\\linewidth,center}\\begin{tabular}").replace("\\end{tabular}", "\\end{tabular}\\end{adjustbox}")
(ROOT / "tables" / "e4_tables.tex").write_text("% generated by report/scripts/make_e4_tables.py from report/data/e4_selection.json\n" + body + "\n" + promo, encoding="utf-8")
print("promoted by the frozen rule:", promoted)
